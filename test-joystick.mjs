import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const dir=mkdtempSync(join(tmpdir(),'voxl-joystick-'));
try {
  const bundle=join(dir,'joystick.mjs');
  execFileSync('esbuild',['web/src/client/joystick.ts','--bundle','--platform=node','--format=esm',`--outfile=${bundle}`]);
  const {joystickVelocity,setupJoystick}=await import(pathToFileURL(bundle));
  assert.deepEqual(joystickVelocity(0,0),[0,0]);
  assert.deepEqual(joystickVelocity(.1,0),[0,0]);
  assert.equal(joystickVelocity(1,0)[0],600);
  const oldNearCenter=260*Math.pow((.3-.16)/(1-.16),2.4);
  assert.ok(joystickVelocity(.3,0)[0]<oldNearCenter*1.02,'fine aiming remains within 2% of the old center speed');
  assert.ok(joystickVelocity(.4,0)[0]<joystickVelocity(.8,0)[0]);
  assert.ok(Math.abs(Math.hypot(...joystickVelocity(1,1))-600)<1e-9);
  globalThis.window=new EventTarget();globalThis.document=new EventTarget();
  const frames=new Map();let sequence=0;
  globalThis.requestAnimationFrame=fn=>{frames.set(++sequence,fn);return sequence;};
  globalThis.cancelAnimationFrame=id=>frames.delete(id);
  const step=time=>{const tasks=[...frames.values()];frames.clear();tasks.forEach(fn=>fn(time));};
  const stick=new EventTarget(),styles={};
  stick.style={setProperty:(k,v)=>styles[k]=v};
  const classes=new Set();stick.classList={add:c=>classes.add(c),remove:c=>classes.delete(c)};
  stick.getBoundingClientRect=()=>({left:0,top:0,width:112,height:112});
  stick.setPointerCapture=()=>{};stick.releasePointerCapture=()=>{};
  const moves=[];let interactions=0;
  const joystick=setupJoystick(stick,(x,y)=>moves.push([x,y]),()=>interactions++);
  function event(type,x=56,y=56,id=1,extra={}){const e=new Event(type,{cancelable:true});Object.assign(e,{clientX:x,clientY:y,pointerId:id,button:0,...extra});stick.dispatchEvent(e);return e;}
  event('pointerdown',70,50);step(0);step(10);
  assert.equal(moves.length,0,'off-center contact starts neutral');
  event('pointermove',104,50);step(10+1000/60);
  assert.equal(moves.length,1);assert.ok(Math.abs(moves[0][0]-600/60)<1e-9);assert.equal(moves[0][1],0);
  assert.equal(interactions,1);assert.equal(styles['--stick-x'],'34px');
  event('pointerdown',22,56,2);step(10+1000/30);assert.ok(moves.at(-1)[0]>0,'second finger cannot take over');
  event('pointerup',90,56);assert.equal(frames.size,0);assert.equal(styles['--stick-x'],'0px');assert.ok(!classes.has('active'));
  event('pointerdown');step(100);step(120);const count=moves.length;assert.equal(count,2,'center does not drift');
  event('pointermove',56,90);step(140);assert.ok(moves.at(-1)[1]>0);
  event('pointercancel');assert.equal(frames.size,0);
  event('pointerdown',90,56);window.dispatchEvent(new Event('blur'));assert.equal(frames.size,0);
  event('pointerdown',90,56);document.hidden=true;document.dispatchEvent(new Event('visibilitychange'));assert.equal(frames.size,0);
  event('keydown',56,56,1,{key:'ArrowLeft'});assert.deepEqual(moves.at(-1),[-12,0]);
  joystick.stop();
  stick.getBoundingClientRect=()=>({left:0,top:0,width:78,height:78});
  event('pointerdown',39,39);event('pointermove',61,39);
  assert.equal(styles['--stick-x'],'22px','thumb travel scales to the compact base');
  event('pointerup');
  console.log('PASS: joystick dead zone, acceleration, bounded diagonal speed, frame timing, multitouch isolation, release/cancel/blur, keyboard control');
} finally {rmSync(dir,{recursive:true,force:true});}
